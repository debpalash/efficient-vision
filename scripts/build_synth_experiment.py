"""Assemble the train/val trees for the synthetic-data experiment.

Three arms, differing only in training data:

  A  real-only        400 real images          (already measured: 0.344 solve)
  B  synthetic-only   N synthetic images       -- tests whether the replica transfers
  C  mixed            N synthetic + 400 real   -- the practical configuration

Arm B never sees a real image, so **all 461 real images** (400 train + 61 val) are
held out for it. That matters: the standard split leaves only 61 val images, where
the standard error near 0.35 is about +/-6 points -- wide enough to swamp the
effect being measured. Evaluating arm B on 461 narrows that to roughly +/-2.

Arms A and C do train on the real 400, so they can only be scored on the 61-image
val set. Their numbers therefore carry the wider error bar, and the comparison
between B-on-461 and A-on-61 is indicative rather than exact. Stated here so the
asymmetry is not silently forgotten when reading the results table.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REAL = ROOT / "datasets" / "project-497" / "src_230x60"


def _link(src: Path, dst: Path) -> None:
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def _copy_split(src_root: Path, split: str, out: Path, out_split: str,
                prefix: str = "") -> int:
    n = 0
    img_dir = src_root / "images" / split
    if not img_dir.is_dir():
        return 0
    for p in sorted(img_dir.iterdir()):
        if not p.is_file():
            continue
        lbl = src_root / "labels" / split / (p.stem + ".txt")
        if not lbl.exists():
            continue
        _link(p, out / "images" / out_split / f"{prefix}{p.name}")
        _link(lbl, out / "labels" / out_split / f"{prefix}{p.stem}.txt")
        n += 1
    return n


def _write_yaml(out: Path, names_src: Path) -> None:
    text = names_src.read_text(encoding="utf-8")
    block = text[text.index("nc:"):]
    (out / "data.yaml").write_text(
        f"# Auto-generated by scripts/build_synth_experiment.py\n"
        f"path: {out.resolve().as_posix()}\ntrain: images/train\nval: images/val\n{block}",
        encoding="utf-8",
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--synth", default=str(ROOT / "datasets" / "synthetic" / "src_230x60_20k"))
    ap.add_argument("--out-root", default=str(ROOT / "datasets" / "experiments"))
    args = ap.parse_args()

    synth = Path(args.synth)
    out_root = Path(args.out_root)
    meta = {}

    # --- arm B: synthetic train, ALL real held out for val -------------------
    b = out_root / "synth_only"
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        (b / sub).mkdir(parents=True, exist_ok=True)
    meta["B_train_synth"] = _copy_split(synth, "train", b, "train")
    meta["B_val_real"] = (
        _copy_split(REAL, "train", b, "val", prefix="rtr_")
        + _copy_split(REAL, "val", b, "val", prefix="rva_")
    )
    _write_yaml(b, REAL / "data.yaml")

    # --- arm C: synthetic + real train, real val -----------------------------
    c = out_root / "mixed"
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        (c / sub).mkdir(parents=True, exist_ok=True)
    meta["C_train_synth"] = _copy_split(synth, "train", c, "train")
    meta["C_train_real"] = _copy_split(REAL, "train", c, "train", prefix="real_")
    meta["C_val_real"] = _copy_split(REAL, "val", c, "val")
    _write_yaml(c, REAL / "data.yaml")

    # --- arm A' : real-only, scored on the SAME 461 images as arm B ----------
    # Arm A was measured on 61 val images. Scoring the existing real-only
    # checkpoint on all 461 would be scoring it on its own training data, which is
    # meaningless -- so this tree exists only to make arm B's val set reproducible,
    # not to re-score arm A.
    meta["note"] = (
        "Arm B is scored on 461 held-out real images; arms A and C on 61. "
        "The 61-image figures carry ~+/-6pp standard error near 0.35."
    )

    (out_root / "experiment_meta.json").write_text(json.dumps(meta, indent=2),
                                                   encoding="utf-8")
    print(json.dumps(meta, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

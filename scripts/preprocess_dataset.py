"""Write a preprocessed copy of a split tree (task #21).

Preprocessing is applied offline rather than in the dataloader so that the
experiment isolates one variable: the two training runs differ only in pixel
content, not in augmentation order, worker count, or caching behaviour.

Labels are copied unchanged -- every pipeline in `efficientvision.data.preprocess`
is pixel-wise or local-neighbourhood and does not move geometry.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _link(src: Path, dst: Path) -> None:
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "datasets" / "project-497" / "yolo3"))
    ap.add_argument("--out", default=None)
    ap.add_argument("--pipeline", default="median_clahe")
    args = ap.parse_args()

    import cv2

    from efficientvision.data.preprocess import apply_pipeline

    src = Path(args.src)
    out = Path(args.out) if args.out else src.parent / f"{src.name}_{args.pipeline}"

    counts = {}
    for split in ("train", "val", "test"):
        img_dir = src / "images" / split
        if not img_dir.is_dir():
            continue
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
        n = 0
        for p in sorted(img_dir.iterdir()):
            if not p.is_file():
                continue
            lbl = src / "labels" / split / (p.stem + ".txt")
            if not lbl.exists():
                continue
            img = cv2.imread(str(p), cv2.IMREAD_COLOR)
            if img is None:
                continue
            cv2.imwrite(str(out / "images" / split / f"{p.stem}.png"),
                        apply_pipeline(img, args.pipeline))
            _link(lbl, out / "labels" / split / lbl.name)
            n += 1
        counts[split] = n

    yaml_src = (src / "data.yaml").read_text(encoding="utf-8")
    block = yaml_src[yaml_src.index("nc:"):]
    (out / "data.yaml").write_text(
        f"# Auto-generated by scripts/preprocess_dataset.py "
        f"(pipeline={args.pipeline})\n"
        f"path: {out.resolve().as_posix()}\ntrain: images/train\nval: images/val\n{block}",
        encoding="utf-8")

    meta = {"source": str(src), "pipeline": args.pipeline, **counts}
    (out / "preprocess_meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(json.dumps(meta, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
